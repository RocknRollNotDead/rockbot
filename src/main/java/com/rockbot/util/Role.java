package com.rockbot.util;

/**
 * Три уровня доступа:
 *
 *  ADMIN    — администратор. Задаётся в .env (ADMIN_IDS).
 *             Может всё: добавлять/удалять участников, управлять контентом.
 *
 *  MEMBER   — участник группы. Добавляется администратором через /addmember.
 *             Хранится в таблице band_members базы данных.
 *             Может добавлять и редактировать песни, читать обратную связь.
 *
 *  LISTENER — слушатель. Все остальные пользователи.
 *             Может просматривать контент и отправлять обратную связь.
 */
public enum Role {
    ADMIN,
    MEMBER,
    LISTENER
}
